#!/usr/bin/env python
"""Build a site-year daily weather download index from the model-ready phenology table."""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("data/phenology/processed/phenology_site_year_stage_1951.csv"),
        help="Prepared site-year-stage phenology table.",
    )
    parser.add_argument("--out-dir", type=Path, default=Path("data/gee"))
    parser.add_argument(
        "--preseason-start-month",
        type=int,
        default=9,
        help="Month in the previous year where weather extraction starts.",
    )
    parser.add_argument(
        "--preseason-start-day",
        type=int,
        default=1,
        help="Day in the previous year where weather extraction starts.",
    )
    return parser.parse_args()


def join_unique(values: pd.Series) -> str:
    items = sorted({str(value) for value in values.dropna() if str(value).strip()})
    return ";".join(items)


def best_model_tier(values: pd.Series) -> str:
    order = {"core": 0, "extended": 1, "sensitivity": 2}
    tiers = [value for value in values.dropna().unique() if value in order]
    if not tiers:
        return "sensitivity"
    return sorted(tiers, key=lambda value: order[value])[0]


def build_weather_index(df: pd.DataFrame, start_month: int, start_day: int) -> pd.DataFrame:
    for column in ["year", "lat", "lon", "alt_m", "event_doy"]:
        df[column] = pd.to_numeric(df[column], errors="coerce")
    df = df.dropna(subset=["country", "source", "site_id", "year", "lat", "lon"]).copy()
    df["year"] = df["year"].astype(int)

    index = (
        df.groupby(["country", "source", "site_id", "year"], dropna=False)
        .agg(
            site_name=("site_name", "first"),
            lat=("lat", "median"),
            lon=("lon", "median"),
            alt_m=("alt_m", "median"),
            n_events=("record_id", "size"),
            bbch_list=("bbch", join_unique),
            phenophase_list=("phenophase", join_unique),
            model_tier=("model_tier", best_model_tier),
            first_event_date=("event_date", "min"),
            last_event_date=("event_date", "max"),
            first_event_doy=("event_doy", "min"),
            last_event_doy=("event_doy", "max"),
        )
        .reset_index()
    )
    index["weather_id"] = (
        index["country"].astype(str)
        + "|"
        + index["source"].astype(str)
        + "|"
        + index["site_id"].astype(str)
        + "|"
        + index["year"].astype(str)
    )
    index["weather_start_date"] = pd.to_datetime(
        {
            "year": index["year"] - 1,
            "month": start_month,
            "day": start_day,
        }
    ).dt.strftime("%Y-%m-%d")
    index["weather_end_date"] = pd.to_datetime(
        {
            "year": index["year"],
            "month": 12,
            "day": 31,
        }
    ).dt.strftime("%Y-%m-%d")
    index["download_status"] = "pending"
    index["weather_source"] = ""
    index["local_weather_path"] = ""

    columns = [
        "weather_id",
        "country",
        "source",
        "site_id",
        "site_name",
        "lat",
        "lon",
        "alt_m",
        "year",
        "weather_start_date",
        "weather_end_date",
        "n_events",
        "bbch_list",
        "phenophase_list",
        "model_tier",
        "first_event_date",
        "last_event_date",
        "first_event_doy",
        "last_event_doy",
        "download_status",
        "weather_source",
        "local_weather_path",
    ]
    return index[columns].sort_values(["country", "source", "site_id", "year"]).reset_index(drop=True)


def write_readme(out_dir: Path) -> None:
    readme_path = out_dir / "README.md"
    existing = readme_path.read_text(encoding="utf-8") if readme_path.exists() else "# Google Earth Engine weather export inputs\n"
    section = """\n## Weather Download Index\n\nGenerated by `src/base_table/build_weather_download_index.py`.\n\nOutput:\n\n- `weather_download_index_1951.csv`\n\nEach row is one `site_id x year` extracted from `data/phenology/processed/phenology_site_year_stage_1951.csv`.\nThe default daily weather window is previous-year September 1 to current-year December 31,\nwhich supports both winter chilling and within-year forcing feature construction.\n\nPlaceholder fields `download_status`, `weather_source`, and `local_weather_path` are included\nfor later weather download workflows. No weather values are stored in this index.\n"""
    if "## Weather Download Index" not in existing:
        readme_path.write_text(existing.rstrip() + "\n" + section, encoding="utf-8")


def main() -> int:
    args = parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    df = pd.read_csv(args.input, low_memory=False)
    index = build_weather_index(df, args.preseason_start_month, args.preseason_start_day)
    out_path = args.out_dir / "weather_download_index_1951.csv"
    index.to_csv(out_path, index=False)
    write_readme(args.out_dir)
    print(f"Weather index rows written: {len(index):,}")
    print(index.groupby("country").size().to_string())
    print(f"Output: {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

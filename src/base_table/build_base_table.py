#!/usr/bin/env python
"""Build the 1951+ six-country standard-BBCH base table."""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd


COUNTRY_ORDER = ["France", "Germany", "Austria", "Switzerland", "Slovakia", "Spain"]
BASE_COLUMNS = [
    "source_system",
    "source_dataset",
    "country",
    "country_name",
    "site_id",
    "site_name",
    "latitude",
    "longitude",
    "altitude",
    "altitude_reported",
    "altitude_ign",
    "altitude_source",
    "date",
    "year",
    "month",
    "day",
    "doy",
    "bbch_standard",
    "bbch_major",
    "phenophase_standard",
    "phenophase_order",
    "bbch_mapping_confidence",
    "bbch_mapping_note",
    "stage_id",
    "stage_code",
    "bbch_code",
    "stage_event",
    "stage_description",
    "cultivar",
    "cultivar_group",
    "taxon_id",
    "taxon_name",
    "taxon_fullname",
    "region",
    "department",
    "commune",
    "natural_region",
    "federal_state",
    "datasource_id",
    "datasource_name",
    "reporter_type",
    "quality_level",
    "date_quality_flag",
    "source_file",
    "observation_id",
    "dedup_group_id",
    "is_training_record",
    "n_years_site_bbch",
    "n_observations_site_bbch",
]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("data/phenology/derived/standardized_bbch/six_country_phenology_bbch_standardized.csv"),
        help="Six-country standardized-BBCH table generated by src/standardize_bbch_analysis_layer.py.",
    )
    parser.add_argument("--out-dir", type=Path, default=Path("data/phenology/derived/base_table"))
    parser.add_argument("--start-year", type=int, default=1951)
    return parser.parse_args()


def load_standardized(path: Path) -> pd.DataFrame:
    header = pd.read_csv(path, nrows=0)
    usecols = [column for column in BASE_COLUMNS if column in header.columns and not column.startswith("n_")]
    df = pd.read_csv(path, usecols=usecols, low_memory=False)
    for column in BASE_COLUMNS:
        if column not in df.columns:
            df[column] = pd.NA
    return df


def build_base_table(df: pd.DataFrame, start_year: int) -> pd.DataFrame:
    for column in [
        "year",
        "month",
        "day",
        "doy",
        "latitude",
        "longitude",
        "altitude",
        "altitude_reported",
        "altitude_ign",
        "phenophase_order",
    ]:
        df[column] = pd.to_numeric(df[column], errors="coerce")

    base = df[
        df["country_name"].isin(COUNTRY_ORDER)
        & df["year"].ge(start_year)
        & df["site_id"].notna()
        & df["date"].notna()
        & df["doy"].between(1, 366)
        & df["latitude"].notna()
        & df["longitude"].notna()
        & df["bbch_standard"].notna()
        & df["bbch_standard"].astype(str).str.strip().ne("")
    ].copy()

    base["year"] = base["year"].astype("Int64")
    for column in ["month", "day", "phenophase_order"]:
        base[column] = base[column].astype("Int64")
    base["bbch_standard"] = base["bbch_standard"].map(normalize_bbch_string)
    base["bbch_major"] = base["bbch_major"].map(normalize_int_string)
    base["site_bbch_key"] = (
        base["country_name"].astype(str)
        + "|"
        + base["source_system"].astype(str)
        + "|"
        + base["site_id"].astype(str)
        + "|"
        + base["bbch_standard"].astype(str)
    )

    continuity = (
        base.groupby("site_bbch_key", dropna=False)
        .agg(
            n_years_site_bbch=("year", "nunique"),
            n_observations_site_bbch=("doy", "size"),
        )
        .reset_index()
    )
    base = base.drop(columns=["n_years_site_bbch", "n_observations_site_bbch"], errors="ignore")
    base = base.merge(continuity, on="site_bbch_key", how="left")
    base = base.drop(columns=["site_bbch_key"])

    base["country_name"] = pd.Categorical(base["country_name"], categories=COUNTRY_ORDER, ordered=True)
    base = base.sort_values(["country_name", "site_id", "bbch_standard", "year", "doy", "date"])
    base["country_name"] = base["country_name"].astype(str)
    return base[BASE_COLUMNS]


def normalize_int_string(value: object) -> str:
    if value is None or pd.isna(value):
        return ""
    text = str(value).strip()
    if not text or text.lower() == "nan":
        return ""
    try:
        return str(int(float(text)))
    except ValueError:
        return text


def normalize_bbch_string(value: object) -> str:
    text = normalize_int_string(value)
    if not text:
        return ""
    return text.zfill(2) if text.isdigit() and int(text) < 100 else text


def write_summaries(base: pd.DataFrame, out_dir: Path, start_year: int, stem: str) -> None:
    country_summary = (
        base.groupby("country_name", dropna=False)
        .agg(
            n_observations=("site_id", "size"),
            n_sites=("site_id", "nunique"),
            first_year=("year", "min"),
            last_year=("year", "max"),
            n_years=("year", "nunique"),
            n_bbch_standard=("bbch_standard", "nunique"),
            n_phenophase_standard=("phenophase_standard", lambda value: value[value.astype(str).str.len().gt(0)].nunique()),
            median_site_bbch_years=("n_years_site_bbch", "median"),
            records_high_confidence=("bbch_mapping_confidence", lambda value: value.eq("high").sum()),
            records_medium_confidence=("bbch_mapping_confidence", lambda value: value.eq("medium").sum()),
        )
        .reindex(COUNTRY_ORDER)
        .reset_index()
    )
    country_summary.to_csv(out_dir / f"{stem}_country_summary.csv", index=False)

    site_bbch_summary = (
        base.groupby(["country_name", "source_system", "site_id", "bbch_standard", "phenophase_standard"], dropna=False)
        .agg(
            site_name=("site_name", "first"),
            latitude=("latitude", "first"),
            longitude=("longitude", "first"),
            altitude=("altitude", "median"),
            first_year=("year", "min"),
            last_year=("year", "max"),
            n_years=("year", "nunique"),
            n_observations=("doy", "size"),
            median_doy=("doy", "median"),
        )
        .reset_index()
        .sort_values(["country_name", "site_id", "bbch_standard"])
    )
    site_bbch_summary.to_csv(out_dir / f"{stem}_site_bbch_summary.csv", index=False)

    readme = f"""# Six-country base table

Generated by `src/base_table/build_base_table.py`.

Main table:

- `{stem}.csv`

Filtering rules:

- Countries: France, Germany, Austria, Switzerland, Slovakia, Spain
- Year: `year >= {start_year}`
- Required fields: `site_id`, `date`, `doy`, `latitude`, `longitude`, `bbch_standard`
- DOY restricted to 1-366
- Standard BBCH fields are inherited from `data/phenology/derived/standardized_bbch/six_country_phenology_bbch_standardized.csv`
- DEM and weather fields are not included yet

Continuity fields:

- `n_years_site_bbch`: number of distinct years for each country/source/site/standard-BBCH combination
- `n_observations_site_bbch`: number of observations for each country/source/site/standard-BBCH combination

Companion summaries:

- `{stem}_country_summary.csv`
- `{stem}_site_bbch_summary.csv`
"""
    (out_dir / "README.md").write_text(readme, encoding="utf-8")


def main() -> int:
    args = parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    df = load_standardized(args.input)
    base = build_base_table(df, args.start_year)
    stem = f"six_country_base_table_{args.start_year}"
    out_path = args.out_dir / f"{stem}.csv"
    base.to_csv(out_path, index=False)
    write_summaries(base, args.out_dir, args.start_year, stem)
    print(f"Rows written: {len(base):,}")
    print(f"Unique sites: {base['site_id'].nunique():,}")
    print(f"Countries: {', '.join(COUNTRY_ORDER)}")
    print(f"Output: {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

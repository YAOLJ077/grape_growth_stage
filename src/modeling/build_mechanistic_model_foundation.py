#!/usr/bin/env python
"""Write the frozen dual-temperature four-stage thermal-model comparison contract."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

try:
    from src.modeling.mechanistic_models import (
        TEMPERATURE_BRANCH_COLUMNS,
        default_model_specifications,
    )
except ModuleNotFoundError:  # Direct script execution from the repository root.
    from mechanistic_models import TEMPERATURE_BRANCH_COLUMNS, default_model_specifications


REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_VALIDATION_DIR = (
    REPO_ROOT / "data/phenology/derived/modeling/france_germany_four_stage/validation"
)
DEFAULT_OUTPUT_DIR = (
    REPO_ROOT / "data/phenology/derived/modeling/france_germany_four_stage/model_setup"
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--validation-dir", type=Path, default=DEFAULT_VALIDATION_DIR)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    return parser.parse_args()


def build_registry() -> pd.DataFrame:
    return pd.DataFrame([specification.as_record() for specification in default_model_specifications()])


def build_comparison_matrix(registry: pd.DataFrame) -> pd.DataFrame:
    branches = pd.DataFrame(
        [
            {
                "temperature_branch": branch,
                "temperature_mean_column": columns["tmean"],
                "temperature_min_column": columns["tmin"],
                "temperature_max_column": columns["tmax"],
            }
            for branch, columns in TEMPERATURE_BRANCH_COLUMNS.items()
        ]
    )
    matrix = registry.merge(branches, how="cross")
    matrix["same_structure_temperature_pair_key"] = matrix["model_id"]
    matrix["outer_validation"] = "frozen_1deg_weather_block_5fold"
    matrix["inner_selection"] = "outer_specific_1deg_weather_block_4fold"
    matrix["execution_status"] = matrix["parameter_status"].map(
        {
            "ready_for_nested_cv": "implementation_ready_not_executed",
            "ready_fixed_external": "implementation_ready_not_executed",
        }
    )
    return matrix.sort_values(["stage", "model_id", "temperature_branch"]).reset_index(drop=True)


def write_readme(path: Path) -> None:
    path.write_text(
        """# Mechanistic model foundation

Generated by `src/modeling/build_mechanistic_model_foundation.py`.

- `mechanistic_model_registry.csv` defines the frozen fixed-reference and calibrated thermal-model structures.
- `dual_temperature_model_comparison_matrix.csv` expands every structure to raw and 6.5 degC/km adjusted temperature branches using identical frozen folds.
- `modeling_contract.json` records temperature columns, fold inputs and leakage constraints.

No full-data model has been fitted. Calibrated thresholds must be estimated only inside the corresponding inner or outer training fold. Fully external benchmarks are limited to the literature-supported budburst GDD5 and flowering/veraison GFV cultivar-median thresholds. Maturity/harvest thresholds are never invented: seasonal and post-veraison GDD10 thresholds are fitted in the active training fold.
""",
        encoding="utf-8",
    )


def main() -> int:
    args = parse_args()
    required_validation = [
        "modeling_event_index.csv",
        "outer_spatial_block_folds.csv",
        "inner_spatial_block_folds.csv",
        "validation_design_summary.json",
    ]
    missing = [name for name in required_validation if not (args.validation_dir / name).exists()]
    if missing:
        raise FileNotFoundError(f"Frozen validation inputs are missing: {missing}")
    validation_summary = json.loads(
        (args.validation_dir / "validation_design_summary.json").read_text(encoding="utf-8")
    )
    if any(validation_summary["leakage_checks"].values()):
        raise ValueError("Frozen validation design has a nonzero leakage check")

    registry = build_registry()
    matrix = build_comparison_matrix(registry)
    contract = {
        "scope": validation_summary["study_scope"],
        "modeling_event_index": str(
            (args.validation_dir / "modeling_event_index.csv").relative_to(REPO_ROOT)
        ),
        "outer_fold_mapping": str(
            (args.validation_dir / "outer_spatial_block_folds.csv").relative_to(REPO_ROOT)
        ),
        "inner_fold_mapping": str(
            (args.validation_dir / "inner_spatial_block_folds.csv").relative_to(REPO_ROOT)
        ),
        "temperature_branches": TEMPERATURE_BRANCH_COLUMNS,
        "n_model_structures": int(len(registry)),
        "n_temperature_model_combinations": int(len(matrix)),
        "calibration_rule": "All fitted forcing thresholds are estimated inside the active training fold only.",
        "comparison_rule": "Raw and adjusted branches use identical observations, outer folds and inner folds.",
        "primary_sample_rule": "Core and extended events are pooled with equal status and weight; tier is not a predictor or stratification variable. Sensitivity events are excluded from the primary analysis.",
        "fixed_reference_rule": "Only literature-supported cultivar-median external benchmarks are executable; no universal BBCH89 threshold is imposed.",
        "execution_state": "foundation_ready; completed runs are recorded in baseline_mechanistic/run_summary.json",
    }
    args.output_dir.mkdir(parents=True, exist_ok=True)
    registry.to_csv(args.output_dir / "mechanistic_model_registry.csv", index=False)
    matrix.to_csv(args.output_dir / "dual_temperature_model_comparison_matrix.csv", index=False)
    (args.output_dir / "modeling_contract.json").write_text(
        json.dumps(contract, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    write_readme(args.output_dir / "README.md")
    print("Mechanistic model foundation")
    print(json.dumps(contract, ensure_ascii=False, indent=2))
    print("\nStructures by stage")
    print(registry.groupby(["stage", "family", "parameter_status"]).size().to_string())
    print(f"\nOutput: {args.output_dir.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
